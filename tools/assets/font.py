# Font palette: 1 = text, 2 = shadow. Several color variants are exported.
FONT_PALETTES = {
    'white': [(0, 0, 0), (248, 248, 240), (24, 20, 28)],
    'yellow': [(0, 0, 0), (255, 214, 40), (40, 24, 8)],
    'red': [(0, 0, 0), (255, 72, 56), (40, 8, 8)],
    'green': [(0, 0, 0), (110, 240, 90), (8, 32, 8)],
    'grey': [(0, 0, 0), (150, 150, 160), (24, 20, 28)],
    'gold': [(0, 0, 0), (240, 190, 70), (60, 30, 8)],
    'blue': [(0, 0, 0), (110, 180, 255), (8, 16, 40)],
    'purple': [(0, 0, 0), (200, 140, 255), (30, 8, 40)],
}


def glyph_canvas(ch):
    rows = G[ch]
    c = Canvas(8, 8)
    for y, row in enumerate(rows):
        for x, p in enumerate(row):
            if p == '#':
                c.set(x, y, 1)
    # Drop shadow.
    for y in range(7, -1, -1):
        for x in range(7, -1, -1):
            if c.get(x, y) == 1:
                for dx, dy in ((1, 0), (1, 1), (0, 1)):
                    if c.get(x + dx, y + dy) == 0 and x + dx < 8 and y + dy < 8:
                        c.set(x + dx, y + dy, 2)
    return c


def generate():
    chars = [chr(i) for i in range(32, 127)]
    frames = [glyph_canvas(ch) for ch in chars[1:]]  # Space has no graphics.
    widths = [max(len(r) for r in G[ch]) + 1 for ch in chars]
    body = emit_sprite_item('font', frames, FONT_PALETTES['white'])
    body += 'inline constexpr int8_t font_widths[] = {%s};\n\n' % ', '.join(str(w) for w in widths)
    for name, pal in FONT_PALETTES.items():
        pal = pal + [(0, 0, 0)] * (16 - len(pal))
        body += 'inline constexpr bn::color font_%s_colors_data[16] = {%s};\n' % (
            name, ', '.join('bn::color(%d, %d, %d)' % (c[0] >> 3, c[1] >> 3, c[2] >> 3) for c in pal))
        body += 'inline constexpr bn::sprite_palette_item font_%s_palette(bn::span<const bn::color>(font_%s_colors_data), ' \
                'bn::bpp_mode::BPP_4);\n' % (name, name)
    body += 'inline constexpr bn::sprite_font sprite_font(font, bn::utf8_characters_map_ref(), ' \
            'bn::span<const int8_t>(font_widths), 0);\n'
    return body
